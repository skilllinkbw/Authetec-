"""Social trust benchmark harness (SYNTHETIC profiles).

IMPORTANT — ACCURACY POLICY
---------------------------
All metrics produced here are measured on **synthetic** profiles
generated by this script.  They demonstrate the rule engine's decision
behaviour, threshold sensitivity and separation quality on constructed
data — they are NOT evidence of real-world fraud-detection accuracy and
must never be quoted as such.  Real validation requires labelled
production profiles.

Usage:
    python -m benchmarks.social.run_social_benchmark
"""

from __future__ import annotations

import argparse
import json
import platform
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

from app.engines.social import SocialProfileInput, SocialTrustEngine

REPORTS_DIR = Path(__file__).resolve().parents[1] / "reports"
MODEL_VERSION = SocialTrustEngine.MODEL_VERSION


def _benign_base(username: str) -> dict:
    return {
        "username": username,
        "email_verified": True,
        "phone_verified": True,
        "email_domain": "example.com",
        "profile_image_present": True,
        "bio_present": True,
        "post_count": 50,
        "following_count": 40,
        "follower_count": 30,
        "declared_country": "bw",
        "phone_calling_code": "267",
        "name_matches_document": True,
    }


def _generate_profiles(n: int, seed: int) -> tuple[list, list]:
    """Generate n labelled profiles (True=suspicious).

    Synthetic generator, clearly documented as such.  Suspicious
    profiles receive a random subset of known abuse markers; benign
    profiles receive none.  This is a harness fixture, not real data.
    """
    rng = np.random.default_rng(seed)
    suspicious: list[SocialProfileInput] = []
    benign: list[SocialProfileInput] = []

    for i in range(n):
        benign.append(SocialProfileInput(
            **_benign_base(f"user_{i}"),
            profile_id=f"benign-{i}",
            account_age_days=int(rng.uniform(200, 3000)),
            post_frequency_per_day=float(rng.uniform(0.1, 3.0)),
        ))

        susp_kwargs = _benign_base(f"u{i:03d}{int(rng.integers(1e6, 1e7))}")
        susp_kwargs.update({
            "profile_id": f"susp-{i}",
            "account_age_days": float(rng.uniform(0.05, 5)),
            "email_verified": bool(rng.integers(0, 2)),
            "phone_verified": False,
            "email_domain": "mailinator.com",
            "post_frequency_per_day": float(rng.uniform(30, 200)),
            "suspension_history_count": int(rng.integers(0, 4)),
            "network_risk": float(rng.uniform(0.3, 1.0)),
        })
        suspicious.append(SocialProfileInput(**susp_kwargs))

    return benign, suspicious


def _precision_recall_f1(tp: int, fp: int, fn: int):
    precision = tp / (tp + fp) if (tp + fp) else None
    recall = tp / (tp + fn) if (tp + fn) else None
    f1 = (2 * precision * recall / (precision + recall)) if (precision and recall) else None
    return precision, recall, f1


def evaluate(n: int = 400, seed: int = 11) -> dict:
    engine = SocialTrustEngine()
    benign, suspicious = _generate_profiles(n, seed)

    scores, labels, decisions = [], [], []
    t0 = time.perf_counter()
    for p in benign:
        r = engine.score(p)
        scores.append(r.risk_score)
        labels.append(0)
        decisions.append(r.decision.value)
    for p in suspicious:
        r = engine.score(p)
        scores.append(r.risk_score)
        labels.append(1)
        decisions.append(r.decision.value)
    latency_ms = (time.perf_counter() - t0) * 1000 / (2 * n)

    labels_arr = np.array(labels, dtype=int)
    decisions_arr = np.array(decisions)

    flagged = decisions_arr != "CLEAR"
    tp = int(flagged[n:].sum())          # suspicious caught
    fn = n - tp
    fp = int(flagged[:n].sum())          # benign false alarms
    tn = n - fp
    precision, recall, f1 = _precision_recall_f1(tp, fp, fn)

    result = {
        "model": "social-rule-engine",
        "model_version": MODEL_VERSION,
        "benchmark_class": "SYNTHETIC",
        "dataset": {
            "name": "authetec-social-profile-generator",
            "version": "v1",
            "n_profiles": 2 * n,
            "n_benign": n,
            "n_suspicious": n,
            "generator": "Random profile markers (harness fixture, not real users)",
        },
        "hardware": {"platform": platform.platform(), "processor": platform.processor()},
        "metrics": {
            "precision": round(precision, 4) if precision is not None else None,
            "recall": round(recall, 4) if recall is not None else None,
            "f1": round(f1, 4) if f1 is not None else None,
            "suspicious_caught_pct": round(100.0 * recall, 2) if recall else None,
            "benign_false_alarm_pct": round(100.0 * fp / n, 2) if n else None,
            "confusion_matrix": {"tp": tp, "fp": fp, "fn": fn, "tn": tn},
            "auc_pr": None,
            "auc_roc": None,
        },
        "thresholds": {
            "clear": engine._thresholds["clear"],
            "review": engine._thresholds["review"],
        },
        "latency_ms": round(latency_ms, 4),
        "limitations": [
            "SYNTHETIC profiles generated by the harness — not real users.",
            "No real fraud dataset has been evaluated; metrics are harness-only.",
            "Rule engine, not a learned model: PR-AUC / ROC-AUC are not applicable.",
            "The engine never uses protected attributes and never decides on a single signal.",
            "These numbers MUST NOT be quoted as real-world social-trust accuracy.",
        ],
        "generated_at": datetime.now(timezone.utc).isoformat(),
    }
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description="Social trust benchmark (SYNTHETIC)")
    parser.add_argument("--profiles", type=int, default=400)
    parser.add_argument("--seed", type=int, default=11)
    args = parser.parse_args()

    print("Running SYNTHETIC social trust benchmark...")
    result = evaluate(n=args.profiles, seed=args.seed)

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    json_path = REPORTS_DIR / f"Social_Trust_Synthetic_{stamp}.json"
    md_path = REPORTS_DIR / f"Social_Trust_Synthetic_{stamp}.md"
    json_path.write_text(json.dumps(result, indent=2))

    m = result["metrics"]
    d = result["dataset"]
    md = [
        "# Benchmark Report — Social Trust Engine (SYNTHETIC)",
        "",
        f"**Generated:** {result['generated_at']}",
        f"**Model:** {result['model']} ({result['model_version']})",
        f"**Benchmark class:** {result['benchmark_class']}",
        "",
        "## Dataset",
        f"- Name: {d['name']} v{d['version']}",
        f"- Profiles: {d['n_profiles']} (benign={d['n_benign']}, suspicious={d['n_suspicious']})",
        "",
        "## Metrics",
        "",
        "| Metric | Value |",
        "|--------|-------|",
        f"| Precision | {m['precision']} |",
        f"| Recall | {m['recall']} |",
        f"| F1 | {m['f1']} |",
        f"| Suspicious caught | {m['suspicious_caught_pct']}% |",
        f"| Benign false alarms | {m['benign_false_alarm_pct']}% |",
        f"| Latency | {result['latency_ms']} ms/score |",
        "",
        "## Limitations",
        *[f"- {lim}" for lim in result["limitations"]],
        "",
    ]
    md_path.write_text("\n".join(md))

    print(f"  Precision: {m['precision']}  Recall: {m['recall']}  F1: {m['f1']}")
    print(f"  Suspicious caught: {m['suspicious_caught_pct']}%  "
          f"Benign false alarms: {m['benign_false_alarm_pct']}%")
    print(f"  JSON report: {json_path}")
    print(f"  MD report:   {md_path}")
    print("\n  NOTE: SYNTHETIC results only — not real-world accuracy evidence.")


if __name__ == "__main__":
    main()